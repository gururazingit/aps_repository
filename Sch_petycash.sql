CREATE TABLE cash_book_maintenance (
    transaction_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cashbook_code     VARCHAR2(50) NOT NULL,
    transaction_date  DATE DEFAULT SYSDATE NOT NULL,
    description       VARCHAR2(255) NOT NULL,
    voucher_type      VARCHAR2(10) CHECK (voucher_type IN ('RECEIPT', 'PAYMENT')),
    receipt_amount    NUMBER(15,2) DEFAULT 0.00,
    payment_amount    NUMBER(15,2) DEFAULT 0.00,
    running_balance   NUMBER(15,2) DEFAULT 0.00,
    currency_code     VARCHAR2(3) DEFAULT 'USD' NOT NULL,
    created_by        VARCHAR2(100) DEFAULT USER,
    creation_date     DATE DEFAULT SYSDATE
);

-- Create an index on frequently queried columns for performance
CREATE INDEX idx_cb_code_date ON cash_book_maintenance (cashbook_code, transaction_date);




